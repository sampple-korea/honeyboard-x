#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"

SDK="${SDK:-$HOME/sdk}"
ANDROID_JAR="$SDK/android-36/android.jar"
XAPI_JAR="$SDK/libxposed-api-102.jar"
R8_JAR="$SDK/r8.jar"
OUT=build
KEYSTORE="${KEYSTORE:-$HOME/.config/samsung-rambler/release.keystore}"

rm -rf "$OUT" && mkdir -p "$OUT/classes" "$OUT/dex" "$OUT/apk"

# Gboard API key: never committed. Taken from $GOOGLE_API_KEY or module/local.keys
# (google_api_key=AIza...). Without it the app asks for a key in its settings.
KEY="${GOOGLE_API_KEY:-}"
if [[ -z "$KEY" && -f local.keys ]]; then
    KEY=$(sed -n 's/^google_api_key=//p' local.keys | tr -d '[:space:]')
fi
if [[ -n "$KEY" && ! "$KEY" =~ ^AIza[0-9A-Za-z_-]{35}$ ]]; then
    echo "invalid GOOGLE_API_KEY" >&2; exit 1
fi
mkdir -p "$OUT/gen/dev/sampple/rambler"
cat > "$OUT/gen/dev/sampple/rambler/BuildKeys.java" <<JAVA
package dev.sampple.rambler;
/** Generated by build.sh. */
public final class BuildKeys {
    private BuildKeys() { }
    public static final String GOOGLE_API_KEY = "$KEY";
}
JAVA
echo "Google API key: $([[ -n "$KEY" ]] && echo built in || echo not built in - enter it in the app)"

find src/main/java "$OUT/gen" -name '*.java' > "$OUT/sources.txt"
javac --release 17 -encoding UTF-8 -Xlint:-options -nowarn \
    -cp "$ANDROID_JAR:$XAPI_JAR:libs/*" -d "$OUT/classes" @"$OUT/sources.txt"

java -cp "$R8_JAR" com.android.tools.r8.D8 --release --min-api 31 \
    --lib "$ANDROID_JAR" --classpath "$XAPI_JAR" \
    --output "$OUT/dex" $(find "$OUT/classes" -name '*.class') libs/*.jar

aapt package -f -M src/main/AndroidManifest.xml -S src/main/res -I "$SDK/android-31-aapt.jar" \
    -F "$OUT/apk/unaligned.apk" --min-sdk-version 31 --target-sdk-version 36 \
    --version-code "${VERSION_CODE:-1}" --version-name "${VERSION_NAME:-1.0}"

mkdir -p "$OUT/apk/stage/META-INF/xposed"
cp "$OUT/dex/classes.dex" "$OUT/apk/stage/"
cp src/main/xposed/* "$OUT/apk/stage/META-INF/xposed/"
(cd "$OUT/apk/stage" && zip -q -r ../unaligned.apk classes.dex META-INF)

zipalign -f -p 4 "$OUT/apk/unaligned.apk" "$OUT/apk/aligned.apk"

if [[ ! -f "$KEYSTORE" ]]; then
    mkdir -p "$(dirname "$KEYSTORE")"
    keytool -genkeypair -keystore "$KEYSTORE" -alias rambler -keyalg RSA -keysize 2048 \
        -validity 10000 -storepass rambler -keypass rambler \
        -dname "CN=Samsung Rambler Module" >/dev/null 2>&1
fi
apksigner sign --ks "$KEYSTORE" --ks-pass pass:rambler --key-pass pass:rambler \
    --out "$OUT/HoneyBoardX.apk" "$OUT/apk/aligned.apk"
apksigner verify "$OUT/HoneyBoardX.apk"
echo "built $OUT/HoneyBoardX.apk"
